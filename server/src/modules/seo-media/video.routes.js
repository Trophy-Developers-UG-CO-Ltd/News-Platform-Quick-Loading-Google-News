/**
 * Video SEO routes
 * @module modules/video-seo/video-seo.routes
 */

const express = require('express');
const router  = express.Router();
const SchemaBuilder = require('../../utils/schema-builder');
const SchemaService = require('../seo-schema/schema.service');
const { protect } = require('../../middlewares/auth.middleware');
const { authorize } = require('../../middlewares/role.middleware');

const admin = [protect, authorize('admin')];

// Generate and save VideoObject schema for a page
router.post('/schema', ...admin, async (req, res, next) => {
  try {
    const { pageSlug, video } = req.body;
    if (!pageSlug || !video) return res.status(400).json({ success: false, message: 'pageSlug and video are required' });

    const schema = SchemaBuilder.videoObject(video);
    const saved  = await SchemaService.upsert(pageSlug, 'VideoObject', schema, req.user?._id, { autoGenerated: false });
    res.json({ success: true, data: saved });
  } catch (err) { next(err); }
});

// Get video schema for a page
router.get('/:pageSlug', ...admin, async (req, res, next) => {
  try {
    const doc = await SchemaService.getBySlugAndType(req.params.pageSlug, 'VideoObject');
    res.json({ success: true, data: doc });
  } catch (err) { next(err); }
});

module.exports = router;

