/**
 * Dynamic Schema model
 * Stores page-level structured data (JSON-LD) for injection into frontend.
 * @module modules/schema-engine/schema.model
 */

const mongoose = require('mongoose');

const SCHEMA_TYPES = [
  'Product', 'Article', 'Organization', 'LocalBusiness',
  'FAQPage', 'VideoObject', 'NewsArticle', 'BreadcrumbList',
  'CollectionPage', 'JobPosting', 'Event', 'WebPage', 'WebSite',
  'Person', 'Review', 'AggregateRating', 'HowTo', 'Recipe',
  'SoftwareApplication', 'Course', 'Service',
];

const schemaDocSchema = new mongoose.Schema(
  {
    pageSlug: {
      type: String,
      required: [true, 'Page slug is required'],
      trim: true,
      lowercase: true,
      index: true,
    },
    schemaType: {
      type: String,
      required: [true, 'Schema type is required'],
      enum: SCHEMA_TYPES,
      index: true,
    },
    schemaJSON: {
      type: mongoose.Schema.Types.Mixed,
      required: [true, 'Schema JSON is required'],
    },
    /** Was this generated automatically by rules engine */
    autoGenerated: {
      type: Boolean,
      default: false,
    },
    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },
    resourceId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null,
    },
    resourceModel: {
      type: String,
      default: null,
    },
    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null,
    },
    lastUpdated: {
      type: Date,
      default: Date.now,
    },
  },
  {
    timestamps: true,
    toJSON:   { virtuals: true },
    toObject: { virtuals: true },
  }
);

// One page can have multiple schema types, but only one per type
schemaDocSchema.index({ pageSlug: 1, schemaType: 1 }, { unique: true });

const SchemaDoc = mongoose.model('SeoSchema2', schemaDocSchema, 'seo_schema');
module.exports = SchemaDoc;
module.exports.SCHEMA_TYPES = SCHEMA_TYPES;

