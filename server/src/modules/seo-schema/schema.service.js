/**
 * Schema Engine service
 * Manages page-level JSON-LD structured data storage and auto-generation.
 * @module modules/schema-engine/schema.service
 */

'use strict';

const SchemaDoc = require('./schema.model');
const SchemaBuilder = require('../../utils/schema-builder');

const SchemaService = {

  /**
   * Get all schemas for a given page slug.
   */
  async getBySlug(pageSlug) {
    return SchemaDoc.find({ pageSlug: pageSlug.toLowerCase(), isActive: true }).lean();
  },

  /**
   * Get a specific schema type for a page.
   */
  async getBySlugAndType(pageSlug, schemaType) {
    return SchemaDoc.findOne({
      pageSlug: pageSlug.toLowerCase(),
      schemaType,
      isActive: true,
    }).lean();
  },

  /**
   * Get all schemas of a given type across all pages.
   */
  async getByType(schemaType, { page = 1, limit = 20 } = {}) {
    const skip  = (page - 1) * limit;
    const total = await SchemaDoc.countDocuments({ schemaType, isActive: true });
    const items = await SchemaDoc.find({ schemaType, isActive: true })
      .skip(skip)
      .limit(limit)
      .lean();
    return { items, total, page, pages: Math.ceil(total / limit) };
  },

  /**
   * Upsert a schema document.
   */
  async upsert(pageSlug, schemaType, schemaJSON, userId, opts = {}) {
    const existing = await SchemaDoc.findOne({
      pageSlug: pageSlug.toLowerCase(),
      schemaType,
    });

    if (existing) {
      existing.schemaJSON    = schemaJSON;
      existing.autoGenerated = opts.autoGenerated ?? existing.autoGenerated;
      existing.updatedBy     = userId;
      existing.lastUpdated   = new Date();
      existing.isActive      = true;
      return existing.save();
    }

    return SchemaDoc.create({
      pageSlug:      pageSlug.toLowerCase(),
      schemaType,
      schemaJSON,
      autoGenerated: opts.autoGenerated ?? false,
      resourceId:    opts.resourceId    || null,
      resourceModel: opts.resourceModel || null,
      updatedBy:     userId,
    });
  },

  /**
   * Delete all schemas for a page, or a specific type.
   */
  async delete(pageSlug, schemaType) {
    const filter = { pageSlug: pageSlug.toLowerCase() };
    if (schemaType) filter.schemaType = schemaType;
    return SchemaDoc.deleteMany(filter);
  },

  /**
   * Auto-generate schemas for a product.
   */
  async generateForProduct(product, userId) {
    const pageSlug = `/products/${product.slug?.en || product._id}`;
    const schema   = SchemaBuilder.product({
      name:        product.name?.en   || product.name || '',
      description: product.description?.en || '',
      sku:         product.sku        || '',
      brand:       product.brand      || '',
      images:      product.images     || [],
      url:         pageSlug,
      price:       product.price,
      currency:    'USD',
      inStock:     product.stockStatus !== 'out_of_stock',
    });

    await this.upsert(pageSlug, 'Product', schema, userId, {
      autoGenerated: true,
      resourceId:    product._id,
      resourceModel: 'Product',
    });

    // Breadcrumb
    const breadcrumb = SchemaBuilder.breadcrumb([
      { name: 'Home',     url: '/' },
      { name: 'Products', url: '/products' },
      { name: product.name?.en || product.name || '', url: pageSlug },
    ]);
    await this.upsert(pageSlug, 'BreadcrumbList', breadcrumb, userId, { autoGenerated: true });

    return { product: schema, breadcrumb };
  },

  /**
   * Auto-generate schemas for an article.
   */
  async generateForArticle(article, userId) {
    const pageSlug = `/articles/${article.localizedSlug?.en || article._id}`;
    const schema   = SchemaBuilder.article({
      title:       article.title?.en    || '',
      description: article.seo?.en?.description || article.seo?.description || article.title?.en || '',
      author:      article.author?.name || '',
      image:       article.featuredImage ? [article.featuredImage] : [],
      url:         pageSlug,
      publishedAt: article.publishedAt,
      updatedAt:   article.updatedAt,
      keywords:    article.tags || [],
    });

    await this.upsert(pageSlug, 'Article', schema, userId, {
      autoGenerated: true,
      resourceId:    article._id,
      resourceModel: 'Article',
    });

    const breadcrumb = SchemaBuilder.breadcrumb([
      { name: 'Home',     url: '/' },
      { name: 'Articles', url: '/articles' },
      { name: article.title?.en || '', url: pageSlug },
    ]);
    await this.upsert(pageSlug, 'BreadcrumbList', breadcrumb, userId, { autoGenerated: true });

    if (
      article.videoMeta?.enabled &&
      (article.videoMeta?.directVideoUrl || article.videoMeta?.videoUrl || article.videoMeta?.embedUrl)
    ) {
      const videoSchema = SchemaBuilder.videoObject({
        name: article.title?.en || '',
        description: article.seo?.en?.description || article.excerpt?.en || article.title?.en || '',
        thumbnail: article.videoMeta.thumbnailUrl || article.videoMeta.posterImage || article.featuredImage || '',
        uploadDate: article.videoMeta.uploadDate || article.publishedAt,
        duration: article.videoMeta.duration || '',
        url: article.videoMeta.directVideoUrl || article.videoMeta.videoUrl || '',
        embedUrl: article.videoMeta.embedUrl || '',
      });

      await this.upsert(pageSlug, 'VideoObject', videoSchema, userId, {
        autoGenerated: true,
        resourceId: article._id,
        resourceModel: 'Article',
      });
    }

    return { article: schema, breadcrumb };
  },

  /**
   * Get all schemas formatted for frontend injection.
   * Returns array of JSON-LD objects for a page.
   */
  async getInjectable(pageSlug) {
    const docs = await SchemaDoc.find({ pageSlug: pageSlug.toLowerCase(), isActive: true }).lean();
    return docs.map(d => d.schemaJSON);
  },

  /**
   * Admin: get paginated list with filters.
   */
  async getAll({ page = 1, limit = 20, schemaType, search } = {}) {
    const filter = { isActive: true };
    if (schemaType) filter.schemaType = schemaType;
    if (search) filter.pageSlug = { $regex: search, $options: 'i' };
    const skip  = (page - 1) * limit;
    const total = await SchemaDoc.countDocuments(filter);
    const items = await SchemaDoc.find(filter)
      .sort('-lastUpdated')
      .skip(skip)
      .limit(limit)
      .lean();
    return { items, total, page, pages: Math.ceil(total / limit) };
  },
};

module.exports = SchemaService;

