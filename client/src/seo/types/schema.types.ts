/**
 * Schema Types
 * TypeScript types for the schema engine.
 * @module types/schema.types
 */

export type SchemaType =
  | 'Product'
  | 'Article'
  | 'Organization'
  | 'LocalBusiness'
  | 'FAQPage'
  | 'VideoObject'
  | 'NewsArticle'
  | 'BreadcrumbList'
  | 'CollectionPage'
  | 'JobPosting'
  | 'Event'
  | 'WebPage'
  | 'WebSite'
  | 'Person'
  | 'HowTo'
  | 'Recipe'
  | 'SoftwareApplication'
  | 'Course'
  | 'Service';

export interface SchemaDocument {
  _id?: string;
  pageSlug: string;
  schemaType: SchemaType;
  schemaJSON: Record<string, unknown>;
  autoGenerated: boolean;
  isActive: boolean;
  resourceId?: string | null;
  resourceModel?: string | null;
  lastUpdated?: string;
  updatedAt?: string;
}

export interface ProductSchemaData {
  name: string;
  description?: string;
  sku?: string;
  brand?: string;
  images?: string[];
  url?: string;
  price?: number;
  currency?: string;
  inStock?: boolean;
  ratingValue?: number;
  reviewCount?: number;
}

export interface ArticleSchemaData {
  title: string;
  description?: string;
  author?: string;
  image?: string | string[];
  url?: string;
  publishedAt?: string;
  updatedAt?: string;
  keywords?: string[];
  isNews?: boolean;
}

export interface FAQItem {
  question: string;
  answer: string;
}

export interface BreadcrumbItem {
  name: string;
  url: string;
}

export interface LocalBusinessData {
  name: string;
  description?: string;
  url?: string;
  phone?: string;
  email?: string;
  type?: string;
  address?: {
    street?: string;
    city?: string;
    region?: string;
    postalCode?: string;
    country?: string;
  };
  geo?: { lat: number; lng: number };
  openingHours?: Array<{
    dayOfWeek: string[];
    opens: string;
    closes: string;
  }>;
  image?: string;
  priceRange?: string;
}

